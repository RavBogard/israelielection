export function mapText(lang: Lang) {
  return Object.fromEntries(keys.map((k, i) => [k, copy[lang][i]])) as Record<
    (typeof keys)[number],
    string
  >;
}
export function mapMessage(template: string, ...values: (string | number)[]) {
  return template.replace(/\{(\d+)\}/g, (_, i: string) =>
    String(values[Number(i)]),
  );
}
export function mapDate(iso: string, lang: Lang) {
  const date = new Date(iso);
  return Number.isFinite(+date)
    ? new Intl.DateTimeFormat(locale(lang), {
        dateStyle: "medium",
        timeZone: "Asia/Jerusalem",
      }).format(date)
    : mapText(lang).notAvailable;
}
