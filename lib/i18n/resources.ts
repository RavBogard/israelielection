export function resourcesText(lang: Lang) {
  return Object.fromEntries(
    keys.map((key, i) => [key, copy[lang][i]]),
  ) as Record<(typeof keys)[number], string>;
}
export function resourceFact(template: string, ...values: (string | number)[]) {
  return template.replace(/\{(\d+)\}/g, (_, i: string) =>
    String(values[Number(i)]),
  );
}

