export const timelineKind = (kind: string, lang: Lang) =>
  kinds[lang][["war", "peace", "politics", "law", "society"].indexOf(kind)] ??
  kind;
export const historyKind = (kind: string, lang: Lang) => {
  const i = [
    "party",
    "alliance",
    "merger",
    "partial",
    "split",
    "rename",
    "leader",
    "list",
  ].indexOf(kind);
  return i < 0 ? kind : kinds[lang][5 + i];
};
