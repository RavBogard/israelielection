export function historicalDate(iso: string, lang: Lang) {
  if (!/^\d{4}-\d\d-\d\d$/.test(iso)) return iso;
  return new Intl.DateTimeFormat(locale(lang), {
    calendar: "gregory",
    timeZone: "UTC",
    dateStyle: "long",
  }).format(new Date(`${iso}T12:00:00Z`));
}
export function historicalMonth(month: number, lang: Lang) {
  return new Intl.DateTimeFormat(locale(lang), {
    calendar: "gregory",
    timeZone: "UTC",
    year: "numeric",
    month: "long",
  }).format(
    new Date(
      Date.UTC(1977 + Math.floor(month / 12), ((month % 12) + 12) % 12, 1),
    ),
  );
}
